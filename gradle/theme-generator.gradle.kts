import groovy.json.JsonSlurper
import java.util.Locale

// ./gradlew generateThemes writes every colour the apps read from design/tokens.json. CI runs it and fails on a diff.
// `themes` lists the app's themes; the role values at the top (`color.tokens`) are the default theme's, and every other
// theme overrides only the roles it changes. `color.themes` is the artifact's own platform list (ios, android), not these.

val tokensFile: File = rootProject.file("design/tokens.json")
val androidThemeFile: File = rootProject.file("androidApp/src/main/kotlin/app/vibeyfin/app/theme/GeneratedThemes.kt")
val iosThemeFile: File = rootProject.file("iosApp/iosApp/App/GeneratedTheme.swift")
val themeIdsFile: File = rootProject.file("shared/src/commonMain/kotlin/app/vibeyfin/domain/ThemeIds.kt")
val windowColorsFile: File = rootProject.file("androidApp/src/main/res/values/colors.xml")
val accentColorsetFile: File = rootProject.file("iosApp/iosApp/Assets.xcassets/AccentColor.colorset/Contents.json")
val launchColorsetFile: File = rootProject.file("iosApp/iosApp/Assets.xcassets/LaunchBackground.colorset/Contents.json")

val generatedNotice: String = "Generated by ./gradlew generateThemes from design/tokens.json. Do not edit."

// Roles with no Android value (a preview stand-in, an alias) and the roles iOS takes from Apple's semantic colours
val androidSkippedRoles: Set<String> = setOf("glass", "positive")
val iosBrandRoles: List<String> = listOf(
    "action", "action-pressed", "on-action",
    "spark", "spark-pressed", "on-spark", "spark-soft", "on-spark-soft",
    "tonal", "on-tonal",
    "scrim", "scrim-strong", "progress-track",
    "on-media", "overlay-weak", "overlay", "overlay-strong",
    "avatar-1", "avatar-2", "avatar-3", "avatar-4", "avatar-5", "avatar-6",
)

class ThemeSpec(val id: String, val isDefault: Boolean, val values: Map<String, Map<String, String>>)

fun camelCase(role: String): String {
    val parts: List<String> = role.split("-")

    return parts.first() + parts.drop(1).joinToString("") { part -> part.replaceFirstChar { it.titlecase(Locale.ROOT) } }
}

fun parseColor(value: String): Pair<Int, Double> {
    val trimmed: String = value.trim()

    if (trimmed.startsWith("#")) return Pair(trimmed.drop(1).toInt(16), 1.0)

    val channels: List<String> = Regex("""rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)""").matchEntire(trimmed)!!.groupValues.drop(1)
    val rgb: Int = (channels[0].toInt() shl 16) or (channels[1].toInt() shl 8) or channels[2].toInt()

    return Pair(rgb, channels[3].toDouble())
}

fun kotlinColor(value: String): String {
    val (rgb: Int, alpha: Double) = parseColor(value)
    val alphaByte: Int = Math.round(alpha * 255).toInt()

    return "Color(0x%02X%06X)".format(alphaByte, rgb)
}

fun swiftColor(value: String): String {
    val (rgb: Int, alpha: Double) = parseColor(value)
    val alphaPart: String = if (alpha == 1.0) "" else ", alpha: $alpha"

    return "Color(hex: 0x%06X%s)".format(rgb, alphaPart)
}

fun loadThemes(tokens: Map<*, *>): List<ThemeSpec> {
    val colorTokens: List<Map<*, *>> = ((tokens["color"] as Map<*, *>)["tokens"] as List<*>).map { it as Map<*, *> }
    val base: Map<String, Map<String, String>> = colorTokens
        .filter { it["value"] is Map<*, *> }
        .associate { token ->
            val value: Map<*, *> = token["value"] as Map<*, *>

            (token["name"] as String) to mapOf("ios" to value["ios"] as String, "android" to value["android"] as String)
        }
    val themes: List<Map<*, *>> = (tokens["themes"] as List<*>).map { it as Map<*, *> }

    return themes.map { theme ->
        val overrides: Map<*, *> = theme["overrides"] as Map<*, *>
        val merged: MutableMap<String, Map<String, String>> = base.toMutableMap()

        overrides.forEach { (role, value) ->
            check(role in base) { "Theme ${theme["id"]} overrides unknown role $role" }
            val platforms: Map<*, *> = value as Map<*, *>

            check(role in iosBrandRoles || platforms["ios"] == base.getValue(role as String)["ios"]) {
                "Theme ${theme["id"]} changes $role on iOS, which reads it from Apple's semantic colours; only the brand roles can differ there"
            }

            merged[role as String] = mapOf("ios" to platforms["ios"] as String, "android" to platforms["android"] as String)
        }

        ThemeSpec(theme["id"] as String, theme["default"] == true, merged)
    }
}

fun androidSource(themes: List<ThemeSpec>): String {
    val roles: List<String> = themes.first().values.keys.filter { it !in androidSkippedRoles }
    val lines: MutableList<String> = mutableListOf()

    lines += "// $generatedNotice"
    lines += "package app.vibeyfin.app.theme"
    lines += ""
    lines += "import androidx.compose.ui.graphics.Color"
    lines += ""
    lines += "/** The colour roles of one theme. */"
    lines += "class ThemeColors(values: Map<String, Color>) {"
    roles.forEach { role -> lines += "    val ${camelCase(role)}: Color = values.getValue(\"$role\")" }
    lines += ""
    lines += "    val avatars: List<Color> = listOf(avatar1, avatar2, avatar3, avatar4, avatar5, avatar6)"
    lines += ""
    lines += "    /** Every role by its name in design/tokens.json. */"
    lines += "    val byRole: Map<String, Color> = values"
    lines += "}"
    lines += ""
    lines += "/** Every theme by its id in design/tokens.json. */"
    lines += "object ThemePalettes {"
    lines += "    const val DEFAULT_ID: String = \"${themes.first { it.isDefault }.id}\""
    lines += ""
    lines += "    val all: Map<String, ThemeColors> = mapOf("
    themes.forEach { theme ->
        lines += "        \"${theme.id}\" to ThemeColors("
        lines += "            mapOf("
        theme.values.filterKeys { it !in androidSkippedRoles }.forEach { (role, value) ->
            lines += "                \"$role\" to ${kotlinColor(value.getValue("android"))},"
        }
        lines += "            ),"
        lines += "        ),"
    }
    lines += "    )"
    lines += ""
    lines += "    /** The theme with this id, or the default one when none has it. */"
    lines += "    fun byId(id: String?): ThemeColors = all[id] ?: all.getValue(DEFAULT_ID)"
    lines += "}"

    return lines.joinToString("\n") + "\n"
}

fun swiftBrandProperties(theme: ThemeSpec, indent: String, format: (String) -> String): List<String> =
    iosBrandRoles.map { role -> "${indent}${camelCase(role)}: ${format(theme.values.getValue(role).getValue("ios"))}" }

fun iosSource(themes: List<ThemeSpec>): String {
    val lines: MutableList<String> = mutableListOf()

    lines += "// $generatedNotice"
    lines += "import SwiftUI"
    lines += ""
    lines += "/// The colour roles with no Apple equivalent, for one theme. The rest are Apple's semantic colours."
    lines += "struct BrandPalette {"
    iosBrandRoles.forEach { role -> lines += "    let ${camelCase(role)}: Color" }
    lines += ""
    lines += "    var avatars: [Color] { [avatar1, avatar2, avatar3, avatar4, avatar5, avatar6] }"
    lines += "}"
    lines += ""
    lines += "extension BrandPalette {"
    lines += "    static let defaultId = \"${themes.first { it.isDefault }.id}\""
    lines += "    static var defaultPalette: BrandPalette { ${camelCase(themes.first { it.isDefault }.id)} }"
    lines += ""
    themes.forEach { theme ->
        lines += "    static let ${camelCase(theme.id)} = BrandPalette("
        lines += swiftBrandProperties(theme, "        ", ::swiftColor).joinToString(",\n")
        lines += "    )"
        lines += ""
    }
    lines += "    static let all: [String: BrandPalette] = ["
    themes.forEach { theme -> lines += "        \"${theme.id}\": ${camelCase(theme.id)}," }
    lines += "    ]"
    lines += ""
    lines += "    /// The palette the screens draw with. Set it once the profile's theme is known; a view tree built afterwards reads it."
    lines += "    nonisolated(unsafe) static var active: BrandPalette = defaultPalette"
    lines += ""
    lines += "    /// The theme with this id, or the default one when none has it."
    lines += "    static func byId(_ id: String?) -> BrandPalette {"
    lines += "        id.flatMap { all[\$0] } ?? defaultPalette"
    lines += "    }"
    lines += "}"
    lines += ""
    lines += "/// The brand colours of the active theme."
    lines += "enum Brand {"
    iosBrandRoles.forEach { role ->
        lines += "    static var ${camelCase(role)}: Color { BrandPalette.active.${camelCase(role)} }"
    }
    lines += "    static var avatars: [Color] { BrandPalette.active.avatars }"
    lines += "}"

    return lines.joinToString("\n") + "\n"
}

fun themeIdsSource(themes: List<ThemeSpec>): String {
    val lines: MutableList<String> = mutableListOf()

    lines += "// $generatedNotice"
    lines += "package app.vibeyfin.domain"
    lines += ""
    lines += "/** The ids of the app's themes, which a profile's theme setting accepts. */"
    lines += "object ThemeIds {"
    lines += "    const val DEFAULT: String = \"${themes.first { it.isDefault }.id}\""
    lines += ""
    lines += "    val all: Set<String> = setOf(${themes.joinToString(", ") { "\"${it.id}\"" }})"
    lines += "}"

    return lines.joinToString("\n") + "\n"
}

fun colorsetSource(value: String): String {
    val (rgb: Int, _) = parseColor(value)
    val components: List<String> = listOf(16, 8, 0).map { shift -> "0x%02X".format((rgb shr shift) and 0xFF) }

    return """
        {
          "colors" : [
            {
              "color" : {
                "color-space" : "srgb",
                "components" : {
                  "alpha" : "1.000",
                  "blue" : "${components[2]}",
                  "green" : "${components[1]}",
                  "red" : "${components[0]}"
                }
              },
              "idiom" : "universal"
            }
          ],
          "info" : {
            "author" : "xcode",
            "version" : 1
          }
        }
    """.trimIndent() + "\n"
}

fun windowColorsSource(bg: String): String {
    val (rgb: Int, _) = parseColor(bg)

    return """
        <?xml version="1.0" encoding="utf-8"?>
        <resources>
            <!-- $generatedNotice The default theme's bg, shown before Compose draws. -->
            <color name="window_background">#%06X</color>
        </resources>
    """.trimIndent().format(rgb) + "\n"
}

tasks.register("generateThemes") {
    group = "build"
    description = "Writes the Kotlin and Swift colours, the window colour and the iOS colour sets from design/tokens.json"
    notCompatibleWithConfigurationCache("The generator is script code, which the configuration cache can not store")
    inputs.file(tokensFile)
    outputs.files(androidThemeFile, iosThemeFile, themeIdsFile, windowColorsFile, accentColorsetFile, launchColorsetFile)

    doLast {
        val tokens: Map<*, *> = JsonSlurper().parse(tokensFile) as Map<*, *>
        val themes: List<ThemeSpec> = loadThemes(tokens)
        val default: ThemeSpec = themes.single { it.isDefault }

        androidThemeFile.writeText(androidSource(themes))
        iosThemeFile.writeText(iosSource(themes))
        themeIdsFile.writeText(themeIdsSource(themes))
        windowColorsFile.writeText(windowColorsSource(default.values.getValue("bg").getValue("android")))
        accentColorsetFile.writeText(colorsetSource(default.values.getValue("ink").getValue("ios")))
        launchColorsetFile.writeText(colorsetSource(default.values.getValue("bg").getValue("ios")))
    }
}
